/**
 * 치장은 저마다 색이 달라서 팔레트 키가 겹치면 안 된다.
 * 슬롯마다 다른 키로 바꿔 넣는다 (k→k1/k2/k3, j→j1/j2/j3).
 */
export function remapForSlot(grid: Grid, index: number): Grid {
  return grid.map((row) =>
    row.replaceAll('k', `${index}`).replaceAll('j', `${index + 3}`),
  );
}

export function cosmeticPalette(art: CosmeticArt, index: number): Palette {
  return {
    [`${index}`]: art.color,
    [`${index + 3}`]: art.accent ?? art.color,
  };
}
