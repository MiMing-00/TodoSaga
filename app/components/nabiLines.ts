/** 방금 한 말을 또 하면 대사가 많은 티가 나지 않는다 */
export function pickLine(list: string[], previous?: string | null): string {
  const pool =
    previous && list.length > 1 ? list.filter((l) => l !== previous) : list;
  return pool[Math.floor(Math.random() * pool.length)];
}
